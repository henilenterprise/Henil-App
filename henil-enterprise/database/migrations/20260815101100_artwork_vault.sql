-- ---------- Extend the RBAC module matrix: admin + manager ----------
-- Artwork is a production/design-adjacent capability, matching the
-- rest of Manager's existing scope (clients, products, quotations,
-- invoices, inventory, reports). Not added to sales/accounts/staff by
-- default; grant via a user's assigned_modules if a specific person
-- needs it (e.g. a workshop lead on the STAFF role).
create or replace function public.role_has_module(p_role text, p_module text)
returns boolean
language sql
immutable
as $$
  select case
    when p_role = 'admin' then true
    when p_role = 'manager' then p_module in ('clients', 'products', 'quotations', 'invoices', 'inventory', 'reports', 'artwork')
    when p_role = 'sales' then p_module in ('clients', 'products', 'quotations')
    when p_role = 'accounts' then p_module in ('invoices', 'payments', 'finance', 'expenses', 'reports')
    when p_role = 'staff' then p_module in ('inventory')
    else false
  end;
$$;

-- ---------- Storage bucket ----------
-- PRIVATE (these are the business's own design IP, if anything more
-- sensitive than a customer's one-off drawing) and a larger size
-- limit than project-files (20MB) since complex multi-layer AI/EPS
-- or dense DXF/CAD files commonly run larger than a simple PDF/photo.
insert into storage.buckets (id, name, public, file_size_limit)
values ('artwork-files', 'artwork-files', false, 52428800) -- 50 MB
on conflict (id) do nothing;

drop policy if exists artwork_files_select on storage.objects;
create policy artwork_files_select on storage.objects
  for select using (bucket_id = 'artwork-files' and public.has_module_access('artwork'));

drop policy if exists artwork_files_insert on storage.objects;
create policy artwork_files_insert on storage.objects
  for insert with check (bucket_id = 'artwork-files' and public.has_module_access('artwork'));

drop policy if exists artwork_files_delete on storage.objects;
create policy artwork_files_delete on storage.objects
  for delete using (bucket_id = 'artwork-files' and public.can_delete_module('artwork'));

comment on column public.artwork_versions.file_type is 'Lowercase extension (svg, dxf, pdf, ai, eps, png, jpg, jpeg, dwg) — validated by the application allow-list before upload, same pattern as public.files.';
