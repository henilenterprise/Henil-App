-- ============================================================
-- Henil Enterprise — Database Schema
-- 29. Artwork Vault: artworks, versions, storage, RBAC module
-- ============================================================
-- A manufacturing design archive, separate from the general
-- project-files bucket (customer-submitted drawings attached to a
-- client/quotation/invoice). Artwork Vault entries are the business's
-- OWN design records — reusable across many jobs, explicitly
-- versioned, and searchable by material/thickness/tags in their own
-- right, not just attached to one document.

create table if not exists public.artworks (
  id uuid primary key default gen_random_uuid(),
  artwork_code text not null unique,
  artwork_name text not null,
  client_id uuid references public.clients (id) on delete set null,
  product_id uuid references public.products (id) on delete set null,
  material text,
  thickness text,
  width numeric(10, 2),
  height numeric(10, 2),
  quantity integer,
  notes text,
  tags text[] not null default '{}',
  status text not null default 'ACTIVE',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint chk_artworks_status check (status in ('ACTIVE', 'ARCHIVED')),
  constraint chk_artworks_width check (width is null or width > 0),
  constraint chk_artworks_height check (height is null or height > 0),
  constraint chk_artworks_quantity check (quantity is null or quantity >= 0)
);

create index if not exists idx_artworks_client_id on public.artworks (client_id);
create index if not exists idx_artworks_product_id on public.artworks (product_id);
create index if not exists idx_artworks_tags on public.artworks using gin (tags);
create index if not exists idx_artworks_material on public.artworks (material);

comment on table public.artworks is 'Manufacturing artwork/design archive — reusable design records, distinct from one-off customer files attached to a document (see public.files).';
comment on column public.artworks.artwork_code is 'Human-readable identifier (e.g. ART-00001), auto-generated by set_artwork_code() below — never entered by the app.';

-- Every uploaded file is a VERSION, never a silent overwrite. Old
-- versions are never deleted by the application; "current version"
-- is just a flag on one row, not a replacement of the others.
create table if not exists public.artwork_versions (
  id uuid primary key default gen_random_uuid(),
  artwork_id uuid not null references public.artworks (id) on delete cascade,
  version_number integer not null,
  file_path text not null,
  file_name text not null,
  file_type text,
  file_size bigint,
  is_current boolean not null default false,
  notes text,
  created_at timestamptz not null default now(),

  constraint uq_artwork_versions_number unique (artwork_id, version_number),
  constraint chk_artwork_versions_file_size check (file_size is null or file_size >= 0)
);

create index if not exists idx_artwork_versions_artwork_id on public.artwork_versions (artwork_id);

-- Enforces "at most one current version per artwork" at the database
-- level, not just in application logic — a partial unique index
-- rather than a boolean-and-hope-the-app-remembers-to-flip-it-off.
create unique index if not exists uq_artwork_versions_one_current
  on public.artwork_versions (artwork_id) where (is_current);

comment on table public.artwork_versions is 'Every uploaded revision of an artwork, kept forever. is_current marks which one is authoritative right now; enforced unique per artwork via uq_artwork_versions_one_current.';

-- ---------- updated_at trigger (matches every other table) ----------
create trigger set_updated_at_artworks
  before update on public.artworks
  for each row execute function public.set_updated_at();

-- ---------- Auto-numbering (matches quotations/invoices exactly) ----------
create sequence if not exists public.artwork_code_seq;

create or replace function public.set_artwork_code()
returns trigger
language plpgsql
as $$
begin
  if new.artwork_code is null or new.artwork_code = '' then
    new.artwork_code := 'ART-' || lpad(nextval('public.artwork_code_seq')::text, 5, '0');
  end if;
  return new;
end;
$$;

create trigger trg_set_artwork_code
  before insert on public.artworks
  for each row execute function public.set_artwork_code();

